-- Care & Stay Academy: standalone data model.
-- NOT applied to a hosted project. Review target project and run migration tests first.
-- Roles: content and entitlements are written only by service_role, not browser clients.
begin;

create table if not exists public.academy_courses (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique,
  title text not null,
  published boolean not null default false,
  created_at timestamptz not null default now()
);
create table if not exists public.academy_modules (
  id uuid primary key default gen_random_uuid(),
  course_id uuid not null references public.academy_courses(id) on delete cascade,
  position integer not null check(position > 0),
  title text not null,
  unique(course_id, position)
);
create table if not exists public.academy_lessons (
  id uuid primary key default gen_random_uuid(),
  module_id uuid not null references public.academy_modules(id) on delete cascade,
  position integer not null check(position > 0),
  title text not null,
  body text not null,
  published boolean not null default false,
  unique(module_id, position)
);
create table if not exists public.academy_scenarios (
  id uuid primary key default gen_random_uuid(),
  lesson_id uuid not null references public.academy_lessons(id) on delete cascade,
  position integer not null check(position > 0),
  prompt text not null,
  unique(lesson_id, position)
);
create table if not exists public.academy_choices (
  id uuid primary key default gen_random_uuid(),
  scenario_id uuid not null references public.academy_scenarios(id) on delete cascade,
  position integer not null check(position > 0),
  choice_text text not null,
  feedback text not null,
  unique(scenario_id, position)
);

create table if not exists public.academy_enrollments (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  course_id uuid not null references public.academy_courses(id),
  status text not null default 'pending' check (status in ('pending', 'active', 'expired', 'revoked', 'completed')),
  stripe_customer_id text,
  stripe_subscription_id text unique,
  granted_at timestamptz,
  expires_at timestamptz,
  created_at timestamptz not null default now(),
  unique(user_id,course_id)
);
create index if not exists academy_enrollments_user_idx on public.academy_enrollments(user_id,status);
create table if not exists public.academy_lesson_progress (
  enrollment_id uuid not null references public.academy_enrollments(id) on delete cascade,
  lesson_id uuid not null references public.academy_lessons(id) on delete cascade,
  completed_at timestamptz not null default now(),
  primary key(enrollment_id,lesson_id)
);
create table if not exists public.academy_private_reflections (
  enrollment_id uuid not null references public.academy_enrollments(id) on delete cascade,
  lesson_id uuid not null references public.academy_lessons(id) on delete cascade,
  body text not null default '',
  modified_at timestamptz not null default now(),
  primary key(enrollment_id,lesson_id)
);
create table if not exists public.academy_submissions (
  id uuid primary key default gen_random_uuid(),
  enrollment_id uuid not null references public.academy_enrollments(id) on delete cascade,
  lesson_id uuid not null references public.academy_lessons(id) on delete cascade,
  body text not null,
  submitted_at timestamptz not null default now(),
  unique(enrollment_id, lesson_id)
);
create table if not exists public.academy_reviewer_assignments (
  reviewer_user_id uuid not null references auth.users(id) on delete cascade,
  enrollment_id uuid not null references public.academy_enrollments(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key(reviewer_user_id, enrollment_id)
);
create table if not exists public.academy_reviews (
  submission_id uuid primary key references public.academy_submissions(id) on delete cascade,
  reviewer_user_id uuid not null references auth.users(id),
  decision text not null check(decision in ('approved','changes_requested')),
  feedback text not null default '',
  reviewed_at timestamptz not null default now()
);
create table if not exists public.academy_graduations (
  enrollment_id uuid primary key references public.academy_enrollments(id) on delete cascade,
  approved_by uuid not null references auth.users(id),
  approved_at timestamptz not null default now()
);
create table if not exists public.academy_billing_events (
  stripe_event_id text primary key,
  event_type text not null,
  received_at timestamptz not null default now(),
  processed_at timestamptz,
  processing_error text
);
create table if not exists public.academy_audit_log (
  id bigint generated by default as identity primary key,
  actor_id uuid,
  action text not null,
  target text,
  logged_at timestamptz not null default now()
);

-- Exposed schema: RLS on every Academy table, including server-only tables.
do $$ declare t text; begin
  foreach t in array array[
    'academy_courses','academy_modules','academy_lessons','academy_scenarios','academy_choices',
    'academy_enrollments','academy_lesson_progress','academy_private_reflections',
    'academy_submissions','academy_reviewer_assignments','academy_reviews',
    'academy_graduations','academy_billing_events','academy_audit_log'
  ] loop
    execute format('alter table public.%I enable row level security',t);
    execute format('revoke all on public.%I from anon,authenticated',t);
  end loop;
end $$;

-- Browser roles receive only narrowly scoped operations; service_role maintains course and payment records.
grant select on public.academy_courses,public.academy_modules,public.academy_lessons,
  public.academy_scenarios,public.academy_choices,public.academy_enrollments,
  public.academy_lesson_progress,public.academy_private_reflections,public.academy_submissions,
  public.academy_reviewer_assignments,public.academy_reviews,public.academy_graduations to authenticated;
grant insert,update on public.academy_lesson_progress,public.academy_private_reflections,public.academy_submissions to authenticated;
grant insert,update on public.academy_reviews to authenticated;
-- No browser grant for entitlement creation, reviewer assignment, graduation, billing event, or audit writes.

create policy "enrollment owned" on public.academy_enrollments for select to authenticated
using (user_id = (select auth.uid()));

create policy "course available to enrolled learner" on public.academy_courses for select to authenticated
using (published and exists(
  select 1 from public.academy_enrollments e
  where e.course_id = id and e.user_id = (select auth.uid())
  and e.status in ('active','completed') and (e.expires_at is null or e.expires_at > now())
));
create policy "module available to enrolled learner" on public.academy_modules for select to authenticated
using (exists(select 1 from public.academy_courses c where c.id = course_id));
create policy "lesson available to enrolled learner" on public.academy_lessons for select to authenticated
using (published and exists(select 1 from public.academy_modules m where m.id=module_id));
create policy "scenario available to enrolled learner" on public.academy_scenarios for select to authenticated
using (exists(select 1 from public.academy_lessons l where l.id=lesson_id));
create policy "choice available to enrolled learner" on public.academy_choices for select to authenticated
using (exists(select 1 from public.academy_scenarios s where s.id=scenario_id));

create policy "progress owned read" on public.academy_lesson_progress for select to authenticated
using (exists(select 1 from public.academy_enrollments e where e.id=enrollment_id and e.user_id=(select auth.uid())));
create policy "progress owned insert" on public.academy_lesson_progress for insert to authenticated
with check (exists(select 1 from public.academy_enrollments e where e.id=enrollment_id and e.user_id=(select auth.uid())
  and e.status='active' and (e.expires_at is null or e.expires_at>now()))
  and exists(select 1 from public.academy_lessons l join public.academy_modules m on m.id=l.module_id
    join public.academy_enrollments e on e.course_id=m.course_id
    where l.id=lesson_id and l.published and e.id=enrollment_id));
create policy "progress owned update" on public.academy_lesson_progress for update to authenticated
using (exists(select 1 from public.academy_enrollments e where e.id=enrollment_id and e.user_id=(select auth.uid()) and e.status='active'))
with check (exists(select 1 from public.academy_enrollments e where e.id=enrollment_id and e.user_id=(select auth.uid())
  and e.status='active' and (e.expires_at is null or e.expires_at>now())));

create policy "reflection private read" on public.academy_private_reflections for select to authenticated
using (exists(select 1 from public.academy_enrollments e where e.id=enrollment_id and e.user_id=(select auth.uid())));
create policy "reflection private insert" on public.academy_private_reflections for insert to authenticated
with check (exists(select 1 from public.academy_enrollments e join public.academy_modules m on m.course_id=e.course_id
 join public.academy_lessons l on l.module_id=m.id where e.id=enrollment_id and l.id=lesson_id
 and e.user_id=(select auth.uid()) and e.status='active'
 and (e.expires_at is null or e.expires_at>now())));
create policy "reflection private update" on public.academy_private_reflections for update to authenticated
using (exists(select 1 from public.academy_enrollments e where e.id=enrollment_id and e.user_id=(select auth.uid()) and e.status='active'))
with check (exists(select 1 from public.academy_enrollments e join public.academy_modules m on m.course_id=e.course_id
 join public.academy_lessons l on l.module_id=m.id where e.id=enrollment_id and l.id=lesson_id
 and e.user_id=(select auth.uid()) and e.status='active'
 and (e.expires_at is null or e.expires_at>now())));

create policy "assignments visible to assigned reviewer" on public.academy_reviewer_assignments for select to authenticated
using (reviewer_user_id=(select auth.uid()));
create policy "submission own or assigned reviewer" on public.academy_submissions for select to authenticated
using (
  exists(select 1 from public.academy_enrollments e where e.id=enrollment_id and e.user_id=(select auth.uid()))
  or exists(select 1 from public.academy_reviewer_assignments a where a.enrollment_id=enrollment_id and a.reviewer_user_id=(select auth.uid()))
);
create policy "submission owner insert" on public.academy_submissions for insert to authenticated
with check(exists(select 1 from public.academy_enrollments e join public.academy_modules m on m.course_id=e.course_id
  join public.academy_lessons l on l.module_id=m.id where e.id=enrollment_id and l.id=lesson_id
  and e.user_id=(select auth.uid()) and e.status='active'
  and (e.expires_at is null or e.expires_at>now())));
create policy "submission owner update" on public.academy_submissions for update to authenticated
using(exists(select 1 from public.academy_enrollments e where e.id=enrollment_id and e.user_id=(select auth.uid()) and e.status='active'))
with check(exists(select 1 from public.academy_enrollments e join public.academy_modules m on m.course_id=e.course_id
 join public.academy_lessons l on l.module_id=m.id where e.id=enrollment_id and l.id=lesson_id
 and e.user_id=(select auth.uid()) and e.status='active' and (e.expires_at is null or e.expires_at>now())));

create policy "review visible to learner or reviewer" on public.academy_reviews for select to authenticated
using (reviewer_user_id=(select auth.uid()) or exists(
  select 1 from public.academy_submissions s join public.academy_enrollments e on e.id=s.enrollment_id
  where s.id=submission_id and e.user_id=(select auth.uid())
));
create policy "review assigned insert" on public.academy_reviews for insert to authenticated
with check(reviewer_user_id=(select auth.uid()) and exists(
  select 1 from public.academy_submissions s join public.academy_reviewer_assignments a
  on a.enrollment_id=s.enrollment_id where s.id=submission_id and a.reviewer_user_id=(select auth.uid())
));
create policy "review assigned update" on public.academy_reviews for update to authenticated
using (reviewer_user_id=(select auth.uid()) and exists(
  select 1 from public.academy_submissions s join public.academy_reviewer_assignments a
  on a.enrollment_id=s.enrollment_id where s.id=submission_id and a.reviewer_user_id=(select auth.uid())
))
with check (reviewer_user_id=(select auth.uid()) and exists(
  select 1 from public.academy_submissions s join public.academy_reviewer_assignments a
  on a.enrollment_id=s.enrollment_id where s.id=submission_id and a.reviewer_user_id=(select auth.uid())
));
create policy "graduation learner read" on public.academy_graduations for select to authenticated
using(exists(select 1 from public.academy_enrollments e where e.id=enrollment_id and e.user_id=(select auth.uid())));

commit;
